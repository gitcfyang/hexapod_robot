/**
 * @brief 四象限反正切（使用查表法）
 * @param y Y坐标
 * @param x X坐标
 * @return 角度（0.1度单位，范围 -1800 ~ 1800）
 * @note 利用 atan(|y|/|x|) 查表，再根据象限调整
 *       当 |y|>|x| 时使用补角: atan(|y|/|x|) = 90° - atan(|x|/|y|)
 *       最大误差约 0.5度
 */
int16_t hexapod_atan4(int32_t y, int32_t x)
{
    if (x == 0 && y == 0) return 0;
    if (x == 0) {
        return (y >= 0) ? 900 : -900;
    }
    
    /* 使用绝对值计算比率 */
    int32_t ax = (x < 0) ? -x : x;
    int32_t ay = (y < 0) ? -y : y;
    
    /* 确定象限 */
    uint8_t quad = 0;
    if (x < 0) quad |= 2;  /* 第二/三象限 */
    if (y < 0) quad |= 1;  /* 第三/四象限 */
    
    /* 计算比率并查表 */
    uint8_t index;
    int16_t angle;
    
    if (ay <= ax) {
        /* |y| <= |x|: 角度 [0°, 45°] */
        if (ax == 0) ax = 1;
        index = (uint8_t)((ay * 100) / ax);
        if (index > 100) index = 100;
        angle = (int16_t)atan_table[index] * 10;  /* 0.1度单位 */
    } else {
        /* |y| > |x|: 使用补角 90° - atan(|x|/|y|) */
        if (ay == 0) ay = 1;
        index = (uint8_t)((ax * 100) / ay);
        if (index > 100) index = 100;
        angle = 900 - (int16_t)atan_table[index] * 10;
    }
    
    /* 根据象限调整角度 */
    switch (quad) {
        case 0: /* 第一象限: x>0, y>0 */ break;
        case 1: /* 第四象限: x>0, y<0 */ angle = -angle; break;
        case 2: /* 第二象限: x<0, y>0 */ angle = 1800 - angle; break;
        case 3: /* 第三象限: x<0, y<0 */ angle = -1800 + angle; break;
    }
    
    return angle;
}

/**
 * @brief 平滑控制函数
 */
int16_t smooth_control(int16_t ctrl_input, int16_t ctrl_output, uint8_t divider)
{
    if (divider == 0) divider = 1;
    
    int16_t delta = ctrl_input - ctrl_output;
    int16_t step = delta / divider;
    
    /* 确保至少有一些移动 */
    if (delta != 0 && step == 0) {
        step = (delta > 0) ? 1 : -1;
    }
    
    return ctrl_output + step;
}
