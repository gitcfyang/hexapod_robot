/**
 * @brief 获取正弦值
 * @note 使用查找表，利用 sin(θ)=sin(180°-θ) 对称性
 *       表值范围: sin_table[i] = sin(i*0.5°)*10000, i=0..180
 *       角度单位：0.1度 (900 = 90.0°)
 */
int16_t hexapod_sin(int16_t angle)
{
    bool negative = false;
    
    /* 处理负角度：sin(-θ) = -sin(θ) */
    if (angle < 0) {
        angle = -angle;
        negative = true;
    }
    
    /* 角度归一化到0-3600范围 (0-360度) */
    angle %= 3600;
    
    /* 180-360度: sin(θ) = -sin(θ-180°) */
    int16_t sign = 1;
    if (angle >= 1800) {
        angle -= 1800;
        sign = -1;
    }
    
    /* 0-180度: 利用 sin(θ) = sin(180°-θ) 折叠到 0-90度 */
    if (angle > 900) {
        angle = 1800 - angle;
    }
    
    /* 查表：索引 = angle / 5 (0.5度步进 = 5个0.1度单位) */
    uint16_t index = angle / 5;
    if (index >= SIN_TABLE_SIZE) index = SIN_TABLE_SIZE - 1;
    int16_t result = sin_table[index];
    
    result *= sign;
    
    return negative ? -result : result;
}

/**
 * @brief 获取余弦值
 */
int16_t hexapod_cos(int16_t angle)
{
    /* cos(x) = sin(90° + x) */
    return hexapod_sin(angle + 900);
}

/**
 * @brief 获取反余弦值
 * @param cos_val 余弦值 * 10000，范围 [-10000, 10000]
 * @return 角度（0.1度单位），范围 [0, 1800]
 * @note 使用三段查找表：
 *       表1: cos [0, 9000] → 角度 [180.0°, 25.8°]
 *       表2: cos [9000, 9900] → 角度 [25.8°, 8.1°]  
 *       表3: cos [9900, 10000] → 角度 [8.1°, 0°]
 *       编码: raw = angle_deg * 255 / 180
 *       解码: angle(0.1°) = raw * 1800 / 255
 */
int16_t hexapod_acos(int16_t cos_val)
{
    /* 输入范围：-10000 到 10000 */
    if (cos_val > 10000) cos_val = 10000;
    if (cos_val < -10000) cos_val = -10000;
    
    /* 处理负值情况：acos(-x) = 180° - acos(x) */
    bool negative = false;
    if (cos_val < 0) {
        cos_val = -cos_val;
        negative = true;
    }
    
    uint8_t angle_raw;
    
    /* 根据cos值选择合适的查找表 */
    if (cos_val <= 9000) {
        /* 表1: index 0(cos=10000→0°) ~ 126(cos=0→90°)
           实际cos=9000时index≈12.6，对应25.8° */
        uint16_t index = (10000 - cos_val) * (ACOS_TABLE_SIZE_1 - 1) / 10000;
        if (index >= ACOS_TABLE_SIZE_1) index = ACOS_TABLE_SIZE_1 - 1;
        angle_raw = acos_table_1[index];
    } 
    else if (cos_val <= 9900) {
        /* 表2: index 0(cos=9900→~25.8°→raw≈37) ~ 126(cos=9000→~8.1°→raw≈11)
           索引递减(cos增大角度减小) */
        uint16_t index = (9900 - cos_val) * (ACOS_TABLE_SIZE_2 - 1) / 900;
        if (index >= ACOS_TABLE_SIZE_2) index = ACOS_TABLE_SIZE_2 - 1;
        angle_raw = acos_table_2[index];
    } 
    else {
        /* 表3: index 0(cos=10000→0°) ~ 63(cos=9900→~8.1°→raw≈11)
           索引递增(cos减小角度增大) */
        uint16_t index = (10000 - cos_val) * (ACOS_TABLE_SIZE_3 - 1) / 100;
        if (index >= ACOS_TABLE_SIZE_3) index = ACOS_TABLE_SIZE_3 - 1;
        angle_raw = acos_table_3[index];
    }
    
    /* 解码: raw(0~255) → angle(0.1度单位, 0~1800) */
    int16_t angle = (int16_t)angle_raw * 1800 / 255;
    
    /* 负值补角 */
    return negative ? (1800 - angle) : angle;
}

/**
 * @brief 整数平方根（牛顿迭代法）
 */
uint32_t hexapod_sqrt(uint32_t value)
{
    if (value == 0) return 0;
    
    uint32_t x = value;
    uint32_t y = (x + 1) / 2;
    
    while (y < x) {
        x = y;
        y = (x + value / x) / 2;
    }
    
    return x;
}

